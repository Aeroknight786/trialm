// Command fit-attn fits decode attention efficiency per backend: the share of
// spec memory bandwidth at which llama.cpp reads the KV cache while writing a
// token at depth. It uses the real predictor, so the fit lives in the same
// frame as every other constant, and reports leave-one-device-out error.
//
//	go run ./tools/fit-attn          # report
//	go run ./tools/fit-attn -write   # also regenerate internal/predict/attn_eff.go
package main

import (
	"encoding/csv"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/aeroknight786/trialm/internal/catalog"
	"github.com/aeroknight786/trialm/internal/engine"
	"github.com/aeroknight786/trialm/internal/predict"
)

var models = map[string]string{"llama3-8b": "llama3.1-8b", "llama3-70b": "llama3.3-70b", "qwen3-30b-a3b": "qwen3-coder-30b-a3b", "gpt-oss-20b": "gpt-oss-20b", "gpt-oss-120b": "gpt-oss-120b", "qwen3.5-9b": "qwen3.5-9b"}
var devices = map[string]string{"Jetson Thor": "Jetson AGX Thor", "Ryzen AI Max+ 395 (8060S)": "Radeon 8060S"}

type pair struct {
	device, backend string
	a, ratio        float64 // fitted efficiency; measured slowdown
	short, long     int
	tm              *predict.Timing
	bw              float64
}

func main() {
	write := flag.Bool("write", false, "regenerate internal/predict/attn_eff.go")
	flag.Parse()
	var pairs []pair
	for _, f := range []string{"research/accuracy/bench_data.csv", "research/accuracy/depth_owner.csv"} {
		pairs = append(pairs, load(f)...)
	}
	by := map[string][]pair{}
	for _, p := range pairs {
		by[p.backend] = append(by[p.backend], p)
	}
	names := make([]string, 0, len(by))
	for b := range by {
		names = append(names, b)
	}
	sort.Strings(names)
	fit := map[string]float64{}
	var keep []string // backends whose fit beats the weight-rate model held out
	for _, b := range names {
		ps := by[b]
		fit[b] = median(effs(ps, ""))
		var errNew, errOld []float64
		for _, p := range ps { // leave this device out of the fit
			a := median(effs(ps, p.device))
			if math.IsNaN(a) {
				continue
			}
			errNew = append(errNew, math.Abs(slowdown(p, a*p.bw)/p.ratio-1))
			errOld = append(errOld, math.Abs(slowdown(p, p.tm.EffBandwidth)/p.ratio-1))
		}
		use := len(errNew) > 0 && median(errNew) < median(errOld)
		verdict := "keep the weight rate (no held-out gain)"
		if use {
			keep = append(keep, b)
			verdict = "use"
		} else if len(errNew) == 0 {
			verdict = "keep the weight rate (one device: cannot hold out)"
		}
		fmt.Printf("%-7s n=%2d  efficiency %.2f  held-out error %4.0f%% vs weight-rate %4.0f%%  -> %s\n", b, len(ps), fit[b], 100*median(errNew), 100*median(errOld), verdict)
	}
	if *write {
		var b strings.Builder
		b.WriteString("// Code generated by go run ./tools/fit-attn -write; DO NOT EDIT.\n// Source: research/accuracy/bench_data.csv and depth_owner.csv depth rows.\n\npackage predict\n\n// decodeAttnEff is the fitted share of spec bandwidth at which llama.cpp\n// reads the KV cache while writing a token (median per backend). Only\n// backends where it beats the weight-rate model on held-out devices are\n// listed; the rest read the cache at the weight rate.\nvar decodeAttnEff = map[string]float64{\n")
		for _, n := range keep {
			fmt.Fprintf(&b, "\t%q: %.2f, // n=%d\n", n, fit[n], len(by[n]))
			if n == "metal" {
				fmt.Fprintf(&b, "\t\"mlx\": %.2f, // no MLX depth data: Metal's\n", fit[n])
			}
		}
		b.WriteString("}\n")
		src, err := format.Source([]byte(b.String()))
		if err == nil {
			err = os.WriteFile("internal/predict/attn_eff.go", src, 0644)
		}
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

func load(path string) []pair {
	f, err := os.Open(path)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	recs, err := csv.NewReader(f).ReadAll()
	if err != nil || len(recs) < 2 {
		fmt.Fprintln(os.Stderr, path, err)
		os.Exit(1)
	}
	col := map[string]int{}
	for i, h := range recs[0] {
		col[h] = i
	}
	type key struct{ dev, backend, model, quant, source string }
	groups := map[key]map[int]float64{}
	for _, r := range recs[1:] {
		if r[col["metric"]] != "tg" || models[r[col["model"]]] == "" {
			continue
		}
		d, _ := strconv.Atoi(r[col["depth"]])
		v, _ := strconv.ParseFloat(r[col["measured_tps"]], 64)
		src := ""
		if strings.HasPrefix(r[col["source_url"]], "owner") {
			src = r[col["source_url"]] // owner runs pair within one run
		}
		k := key{r[col["device"]], strings.ToLower(r[col["backend"]]), r[col["model"]], r[col["quant"]], src}
		if groups[k] == nil {
			groups[k] = map[int]float64{}
		}
		groups[k][d] = v
	}
	prof, _ := engine.Get("llamacpp")
	var out []pair
	for k, g := range groups {
		depths := make([]int, 0, len(g))
		for d := range g {
			depths = append(depths, d)
		}
		sort.Ints(depths)
		if len(depths) < 2 {
			continue
		}
		m, ok := catalog.Lookup(models[k.model])
		dev := k.dev
		if devices[dev] != "" {
			dev = devices[dev]
		}
		sys, err := predict.SyntheticSystem(dev, 256, 0)
		if !ok || err != nil {
			continue
		}
		tg := predict.TargetFromSystem(sys, 0)
		backend := ""
		if k.backend == "rocm" || k.backend == "vulkan" {
			backend = k.backend
		}
		res := predict.Predict(predict.Input{Model: m, QuantName: k.quant, Runtime: prof, Target: tg, CtxOverride: 131072, BackendOverride: backend})
		if res.Timing == nil {
			continue
		}
		for _, d := range depths[1:] {
			p := pair{device: k.dev, backend: k.backend, short: depths[0], long: d, ratio: g[depths[0]] / g[d], tm: res.Timing, bw: tg.Device.BandwidthGBs * 1e9}
			// Solve slowdown(B) = ratio for the attention bandwidth B.
			A := p.tm.WeightsBytesPerTok/p.tm.EffBandwidth + p.tm.T0
			ks, kl := p.tm.Model.KVReadBytes(p.short, p.tm.KVElem), p.tm.Model.KVReadBytes(p.long, p.tm.KVElem)
			if B := (kl - p.ratio*ks) / ((p.ratio - 1) * A); B > 0 && p.ratio > 1 {
				p.a = B / p.bw
				out = append(out, p)
			}
		}
	}
	return out
}

func slowdown(p pair, attnBW float64) float64 {
	A := p.tm.WeightsBytesPerTok/p.tm.EffBandwidth + p.tm.T0
	return (A + p.tm.Model.KVReadBytes(p.long, p.tm.KVElem)/attnBW) / (A + p.tm.Model.KVReadBytes(p.short, p.tm.KVElem)/attnBW)
}
func effs(ps []pair, without string) []float64 {
	var v []float64
	for _, p := range ps {
		if p.device != without {
			v = append(v, p.a)
		}
	}
	return v
}
func median(v []float64) float64 {
	if len(v) == 0 {
		return math.NaN()
	}
	s := append([]float64(nil), v...)
	sort.Float64s(s)
	if len(s)%2 == 1 {
		return s[len(s)/2]
	}
	return (s[len(s)/2-1] + s[len(s)/2]) / 2
}
